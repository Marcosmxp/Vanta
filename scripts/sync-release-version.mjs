import fs from 'node:fs';
import path from 'node:path';

const root = process.cwd();
const writeMode = process.argv.includes('--write');

function readJson(relativePath) {
  return JSON.parse(fs.readFileSync(path.join(root, relativePath), 'utf8'));
}

function writeJson(relativePath, value) {
  fs.writeFileSync(path.join(root, relativePath), `${JSON.stringify(value, null, 2)}\n`);
}

function writeText(relativePath, value) {
  fs.writeFileSync(path.join(root, relativePath), value);
}

const metadata = readJson('version.json');
const failures = [];

function expect(condition, message) {
  if (!condition) failures.push(message);
}

expect(metadata.schemaVersion === 1, 'version.json schemaVersion must be 1.');
expect(/^\d+\.\d+\.\d+$/.test(metadata.version ?? ''), 'version.json version must use MAJOR.MINOR.PATCH.');
expect(['alpha', 'beta', 'rc', 'stable'].includes(metadata.channel), 'version.json channel must be alpha, beta, rc or stable.');
expect(Number.isInteger(metadata.build) && metadata.build > 0, 'version.json build must be a positive integer.');

if (metadata.channel === 'stable') {
  expect(metadata.iteration === null || metadata.iteration === undefined, 'Stable releases must not define a prerelease iteration.');
} else {
  expect(Number.isInteger(metadata.iteration) && metadata.iteration > 0, 'Prerelease iteration must be a positive integer.');
}

if (failures.length > 0) {
  console.error('Invalid Vanta canonical version metadata:');
  for (const failure of failures) console.error(`- ${failure}`);
  process.exit(1);
}

const releaseVersion = metadata.channel === 'stable'
  ? metadata.version
  : `${metadata.version}-${metadata.channel}.${metadata.iteration}`;

const generatedReleaseModule = `// Generated from root version.json by scripts/sync-release-version.mjs.\n// Do not edit this file directly.\nexport const releaseMetadata = {\n  productVersion: '${metadata.version}',\n  releaseVersion: '${releaseVersion}',\n  channel: '${metadata.channel}',\n  buildNumber: ${metadata.build},\n} as const;\n`;

const releaseModulePath = 'apps/mobile/src/app/config/releaseMetadata.ts';
const rootPackage = readJson('package.json');
const mobilePackage = readJson('apps/mobile/package.json');
const appConfig = readJson('apps/mobile/app.json');

if (writeMode) {
  rootPackage.version = releaseVersion;
  mobilePackage.version = releaseVersion;
  appConfig.expo.version = metadata.version;
  appConfig.expo.ios = { ...appConfig.expo.ios, buildNumber: String(metadata.build) };
  appConfig.expo.android = { ...appConfig.expo.android, versionCode: metadata.build };

  writeJson('package.json', rootPackage);
  writeJson('apps/mobile/package.json', mobilePackage);
  writeJson('apps/mobile/app.json', appConfig);
  writeText(releaseModulePath, generatedReleaseModule);

  console.log(`Synchronized Vanta ${releaseVersion} build ${metadata.build}.`);
  process.exit(0);
}

expect(rootPackage.version === releaseVersion, `package.json version must be ${releaseVersion}.`);
expect(mobilePackage.version === releaseVersion, `apps/mobile/package.json version must be ${releaseVersion}.`);
expect(appConfig.expo?.version === metadata.version, `Expo marketing version must be ${metadata.version}.`);
expect(appConfig.expo?.ios?.buildNumber === String(metadata.build), `iOS buildNumber must be ${metadata.build}.`);
expect(appConfig.expo?.android?.versionCode === metadata.build, `Android versionCode must be ${metadata.build}.`);
expect(
  fs.existsSync(path.join(root, releaseModulePath)) && fs.readFileSync(path.join(root, releaseModulePath), 'utf8') === generatedReleaseModule,
  `${releaseModulePath} must match version.json.`,
);

if (failures.length > 0) {
  console.error('Vanta release version drift detected:');
  for (const failure of failures) console.error(`- ${failure}`);
  console.error('Run: pnpm release:sync');
  process.exit(1);
}

console.log(`Vanta release metadata is synchronized: ${releaseVersion} (build ${metadata.build}).`);
